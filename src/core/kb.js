// ── 工具说明（由注册表生成，保证与真实实现同源） ──────────────────────────
function toolDocuments(tools) {
  const list = Array.isArray(tools) ? tools : []
  const overview = list.map(tool => `· ${tool.id}（${tool.kind === 'query' ? '查询' : tool.kind === 'navigate' ? '导航' : '操作'}）${tool.summary}`).join('\n')
  const docs = [
    doc(
      'kb.tools.overview',
      'AI 助手可用工具总览',
      `AI 助手通过工具访问应用功能。当前注册的工具：\n${overview}\n`
        + '规则：查询类与导航类工具可直接执行；操作类工具会先向你说明影响并等待确认；'
        + '参数必须有明确来源，缺少关键参数时应先向你询问，不得自行猜测。',
      '工具 列表 能力 总览 注册',
      'tool',
    ),
  ]
  for (const tool of list) {
    const params = Object.entries(tool.params || {})
      .map(([name, spec]) => {
        const required = spec.required ? '必填' : '可选'
        const values = Array.isArray(spec.enum) && spec.enum.length ? `，取值：${spec.enum.join(' / ')}` : ''
        return `${name}（${spec.type}，${required}${values}）：${spec.desc || ''}`
      })
      .join('\n')
    docs.push(doc(
      `kb.tool.${tool.id}`,
      `工具：${tool.id} — ${tool.title}`,
      `${tool.summary}\n用途：${tool.describe || tool.summary}`
        + `\n操作类型：${tool.kind}；风险等级：${tool.risk}；是否需要确认：${tool.needConfirm ? '是' : '否'}`
        + (params ? `\n参数：\n${params}` : '\n参数：无')
        + `\n结果：${tool.resultHint || '返回执行结果摘要'}`,
      `工具 ${tool.id} ${tool.title} 参数`,
      'tool',
    ))
  }
  return docs
}

// 全部知识文档。工具注册表作为参数传入，避免与 tools.js 形成循环依赖。
export function knowledgeDocuments(tools = []) {
  return [...VIEW_DOCS, ...CONCEPT_DOCS, ...FAQ_DOCS, ...toolDocuments(tools)]
}

