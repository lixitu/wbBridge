// AI 助手的知识来源：可被 BM25 检索的「稳定知识」文档集。
//
// 边界（重要）：这里**只放不会频繁变化的知识**——视图说明、动作语义、状态字段含义、
// 使用规则与常见故障处置。模型名单、额度、代理开关等运行态数据**不入索引**：
// 它们随时在变，一旦进索引就可能被模型当成「已核实的事实」引用（过期即误导）。
// 这类问题一律由 tools.js 的实时查询工具回答，答案永远来自当前状态快照。
//
// 因此知识文档的构建是纯函数：只依赖工具注册表（代码的一部分），不依赖运行态。
// 应用功能有任何变化时，这里必须同步更新——它是模型理解本应用的唯一书面依据。
import { fingerprint } from './text.js'

const SOURCE = '应用知识库'
// 最近更新日期：人工维护。检索结果里会带上它，便于判断知识是否陈旧。
const UPDATED_AT = '2026-10-13'

function doc(id, title, body, tags, type = 'knowledge') {
  return {
    id,
    type,
    title,
    body,
    tags,
    source: SOURCE,
    updatedAt: UPDATED_AT,
    perm: 'public',
    fingerprint: fingerprint(`${title}\u0000${tags}\u0000${body}`),
  }
}

